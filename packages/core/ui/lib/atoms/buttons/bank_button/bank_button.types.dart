/// Visual type for the BankButton widget.
enum BankButtonType {
  /// Filled button — high emphasis.
  solid,

  /// Outlined button — medium emphasis.
  outlined,

  /// Soft-filled button — medium-low emphasis.
  subtle,

  /// Transparent button with leading icon and label — low emphasis.
  ghost,

  /// Icon-only transparent button.
  icon,

  /// Filled button with leading icon and label.
  nestedIcon,
}

/// Size for the BankButton widget.
enum BankButtonSize {
  /// Compact — height 36.
  small,

  /// Standard — height 48.
  medium,

  /// Large — height 56.
  large,
}
